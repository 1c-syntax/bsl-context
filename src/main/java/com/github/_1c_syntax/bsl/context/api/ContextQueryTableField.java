package com.github._1c_syntax.bsl.context.api;

/**
 * Поле таблицы языка запросов.
 * <p>
 * Имя двуязычное там, где его задаёт платформа ({@code Период (Period)}),
 * и шаблонное там, где оно берётся из метаданных конфигурации
 * ({@code <Имя реквизита>}, {@code <Имя ресурса>Дт (<Имя ресурса>Dr)}).
 * Шаблон отдаётся как есть: подставить объявленное имя может только
 * потребитель, у которого под рукой метаданные.
 */
public interface ContextQueryTableField {

    /**
     * Имя поля (ru + en).
     */
    ContextName name();

    /**
     * Тип значения поля в том виде, как он записан в синтакс-помощнике
     * ({@code Булево}, {@code БизнесПроцессСсылка.<Имя бизнес-процесса>}).
     * Пустая строка, если на странице поля блока «Тип:» нет: у части полей
     * ({@code ВерсияДанных}, {@code УточнениеПериода}) он не указан.
     */
    default String rawValueType() {
        return "";
    }

    /**
     * Описание поля из синтакс-помощника. Пустая строка, если не задано.
     */
    default String description() {
        return "";
    }

    /**
     * Заметка со страницы поля — блок «Примечание:», уточняющий, при каких
     * настройках объекта метаданных поле существует. Пустая строка, если
     * заметки нет.
     */
    default String notes() {
        return "";
    }

    /**
     * Признак шаблонного имени: в имени стоит плейсхолдер вида
     * {@code <Имя реквизита>}, и материализовать его должен потребитель.
     */
    default boolean isGeneric() {
        return ContextNames.isGeneric(name());
    }
}
