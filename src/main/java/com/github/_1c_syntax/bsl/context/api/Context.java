package com.github._1c_syntax.bsl.context.api;

import java.util.List;

/**
 * Корневой элемент модели — любая именованная сущность синтакс-помощника:
 * платформенный тип ({@link ContextType}), перечисление ({@link ContextEnum}),
 * глобальный контекст или примитив.
 *
 * <p>Получить набор контекстов можно через {@link ContextProvider}.
 */
public interface Context {
    /**
     * Двухъязычное имя (ru + en).
     */
    ContextName name();

    /**
     * Категория контекста (примитив / тип / перечисление / глобальный контекст).
     */
    ContextKind kind();

    /**
     * Признак generic-типа платформы (имя содержит {@code <…>}-плейсхолдер,
     * который заполняется конкретным именем из конфигурации, например
     * {@code СправочникСсылка.<Имя справочника>}). Конкретные типы
     * приходят отдельно из проекта {@code MDClasses}.
     */
    default boolean isGeneric() {
        return ContextNames.isGeneric(name());
    }

    /**
     * Имена generic-плейсхолдеров (без угловых скобок), в порядке появления
     * в qualifiedName типа. Для {@code "СправочникСсылка.<Имя справочника>"}
     * возвращает {@code ["Имя справочника"]}. Для не-generic типа — пустой
     * список.
     * <p>
     * Используется потребителями (например, language-серверами) для
     * структурной работы с дженериками без самостоятельного парсинга
     * угловых скобок.
     */
    default List<String> typeParameters() {
        return ContextNames.typeParameters(name());
    }

    /**
     * Описание контекста из синтакс-помощника — блок «Описание:» главной
     * страницы. Пустая строка, если блока нет.
     */
    default String description() {
        return "";
    }

    /**
     * Заметка со страницы контекста — блок «Примечание:» / «Замечание:»,
     * идущий после «Описание:». Пустая строка, если заметки нет.
     */
    default String notes() {
        return "";
    }

    /**
     * Доступность контекста по видам клиента — блок «Доступность:» главной
     * страницы (например, у {@code Массив} — все клиенты и сервер).
     * Пустой список, если блока нет.
     */
    default List<Availability> availabilities() {
        return List.of();
    }

    /**
     * Версия платформы, начиная с которой доступен контекст (например
     * {@code "8.0"}). Пустая строка, если информации о версии нет.
     */
    default String sinceVersion() {
        return "";
    }

    /**
     * Версия платформы, начиная с которой контекст помечен как не
     * рекомендуемый к использованию. Пустая строка, если контекст актуален.
     */
    default String deprecatedSinceVersion() {
        return "";
    }

    /**
     * Примеры кода со страницы контекста — блоки «Пример:», по одной строке
     * на пример.
     */
    default List<String> examples() {
        return List.of();
    }

    /**
     * Имена связанных контекстов и их членов — блок «См. также:». Члены
     * квалифицированы владельцем ({@code Владелец.Член}).
     */
    default List<String> seeAlso() {
        return List.of();
    }

    /**
     * Имена, рекомендованные в качестве замены устаревшего контекста.
     */
    default List<String> recommendedReplacements() {
        return List.of();
    }

    /**
     * «Семейный префикс» имени — часть имени до первого placeholder'а,
     * обрезанная по последней точке. Для
     * {@code "СправочникСсылка.<Имя справочника>"} даст
     * {@code "СправочникСсылка"}; для {@code "СправочникВыборка.<Имя справочника>"}
     * — {@code "СправочникВыборка"}; для не-generic типа — само имя без
     * изменений.
     * <p>
     * Удобно при группировке дженериков по семействам
     * (СправочникСсылка / СправочникОбъект / СправочникМенеджер /
     * СправочникВыборка имеют общее «ядро» {@code "Справочник"}, но разные
     * familyCore — этот метод возвращает именно конкретный family-префикс
     * данного типа).
     */
    default String familyCore() {
        return ContextNames.familyCore(name());
    }
}
