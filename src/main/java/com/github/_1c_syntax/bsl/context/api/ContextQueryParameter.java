package com.github._1c_syntax.bsl.context.api;

import java.util.List;

/**
 * Параметр функции языка запросов.
 * <p>
 * Структурированного описания параметров в справке нет: они описаны прозой —
 * «Первый параметр – строка, из которой необходимо выделить подстроку.
 * Выражение, имеющее тип СТРОКА». Имя параметра платформа не даёт вовсе,
 * поэтому {@link #position()} — единственный надёжный идентификатор, а
 * {@link #types()} собираются по ссылкам на страницы литералов в тексте.
 *
 * @see ContextQueryElement#parameters()
 */
public interface ContextQueryParameter {

    /** Порядковый номер, начиная с 1. */
    int position();

    /** Описание параметра из справки. */
    String description();

    /** То же с парной en-страницы; пусто, если её нет. */
    default String descriptionEn() {
        return "";
    }

    /**
     * Типы параметра — имена литералов языка запросов ({@code СТРОКА},
     * {@code ЧИСЛО}, {@code ДАТА}), на которые ссылается описание.
     * Пустой список, если в тексте ссылок нет.
     */
    default List<String> types() {
        return List.of();
    }

    /**
     * Необязательный параметр: в синтаксическом правиле он заключён
     * в квадратные скобки.
     */
    default boolean isOptional() {
        return false;
    }
}
