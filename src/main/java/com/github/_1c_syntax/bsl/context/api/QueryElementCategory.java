package com.github._1c_syntax.bsl.context.api;

/**
 * Категория элемента языка запросов. Берётся из ветки оглавления
 * {@code shquery_*.hbk} («Keywords», «Functions», «Operators», «Constants and
 * parameters»), а не из заголовка страницы: заголовки неоднородны
 * («Предложение ВЫБРАТЬ», «Секция ИТОГИ (Описание итогов)», «Псевдонимы полей
 * выборки»), и по ним больше половины страниц оставались нераспознанными.
 *
 * @see ContextQueryElement
 */
public enum QueryElementCategory {
    /**
     * Секция запроса — верхний уровень его структуры: {@code ВЫБРАТЬ},
     * {@code ОБЪЕДИНИТЬ [ВСЕ]}, {@code УПОРЯДОЧИТЬ ПО}, {@code ИТОГИ}.
     */
    SECTION,
    /** Предложение внутри секции: {@code ИЗ}, {@code ГДЕ}, {@code ПОМЕСТИТЬ}, {@code ИМЕЮЩИЕ}. */
    CLAUSE,
    /** Ключевое слово: {@code РАЗЛИЧНЫЕ}, {@code ПЕРВЫЕ}, {@code ИЕРАРХИЯ}, {@code КАК}. */
    KEYWORD,
    /**
     * Функция: {@code ПОДСТРОКА}, {@code РАЗНОСТЬДАТ}, {@code СРЕДНЕЕ}.
     * Вид функции уточняет {@link ContextQueryElement#functionGroup()}.
     */
    FUNCTION,
    /** Оператор: {@code В}, {@code ПОДОБНО}, {@code МЕЖДУ}, {@code ССЫЛКА}. */
    OPERATOR,
    /** Литерал или параметр: {@code ДАТАВРЕМЯ}, {@code ТИП}, {@code NULL}, {@code &Параметр}. */
    LITERAL,
    /**
     * Обзорная статья без собственного имени-конструкции: «Правила сравнения
     * значений», «Разыменование полей», «Комментарии в языке запросов».
     * Имя такого элемента — заголовок страницы целиком.
     */
    ARTICLE
}
