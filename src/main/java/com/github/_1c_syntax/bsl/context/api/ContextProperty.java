package com.github._1c_syntax.bsl.context.api;

import java.util.List;

/**
 * Контекстное свойство.
 */
public interface ContextProperty {
    /**
     * Имя свойства.
     */
    ContextName name();
    /**
     * Режим доступа к свойству.
     */
    AccessMode accessMode();

    /**
     * Доступность свойства
     */
    List<Availability> availabilities();

    /**
     * Типы, которые может принимать свойство
     */
    List<Context> types();

    /**
     * Описание свойства
     */
    String description();

    /**
     * Версия платформы, начиная с которой доступно свойство (например {@code "8.3.27"}).
     * Пустая строка, если информация о версии отсутствует.
     */
    default String sinceVersion() {
        return "";
    }

    /**
     * Версия платформы, начиная с которой свойство помечено как не рекомендуемое
     * к использованию. Пустая строка, если свойство актуально.
     */
    default String deprecatedSinceVersion() {
        return "";
    }

    /**
     * Признак generic-свойства: имя содержит {@code <…>}-плейсхолдер,
     * который соответствует имени объекта из конфигурации (например,
     * свойство {@code <Имя справочника>} на типе {@code СправочникиМенеджер}).
     */
    default boolean isGeneric() {
        return ContextNames.isGeneric(name());
    }

    /**
     * Имена, рекомендованные в качестве замены устаревшего свойства.
     */
    default List<String> recommendedReplacements() {
        return List.of();
    }

    /**
     * Заметка со страницы свойства — блок «Примечание:» / «Замечание:»,
     * идущий после «Описание:». В {@link #description()} он не входит.
     * Если на странице есть только «Примечание:» (без «Описание:»), оно
     * трактуется как описание, а здесь возвращается пустая строка.
     */
    default String notes() {
        return "";
    }

    /**
     * Примеры кода со страницы свойства — блоки «Пример:». Встречаются
     * редко: у большинства свойств примеров в справке нет.
     */
    default List<String> examples() {
        return List.of();
    }

    /**
     * Имена связанных контекстов и их членов — блок «См. также:»
     * (члены квалифицированы владельцем: {@code Владелец.Член}).
     */
    default List<String> seeAlso() {
        return List.of();
    }

    /**
     * Типы элементов коллекции, на которую указывает свойство (per-property element-type).
     * Извлекаются из маркера «Элементами коллекции являются объекты типа …» в описании
     * свойства в синтакс-помощнике. Например, для {@code ОбъектМетаданныхКонфигурация.Документы}
     * — {@code ОбъектМетаданных: Документ}.
     * <p>
     * Отличается от {@link ContextCollection#collectionElementTypes()} тем, что у коллекции
     * метод отдаёт ВСЕ возможные типы элементов на самом типе-коллекции, а у свойства —
     * конкретный тип, который реально вернётся при чтении этого свойства.
     * <p>
     * Пустой список, если маркер на странице отсутствует.
     */
    default List<Context> collectionElementTypes() {
        return List.of();
    }

}
