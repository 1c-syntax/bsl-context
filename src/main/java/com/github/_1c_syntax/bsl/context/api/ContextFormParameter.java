package com.github._1c_syntax.bsl.context.api;

import java.util.List;

/**
 * Параметр формы — элемент секции «Параметры формы:» на странице типа-формы
 * синтакс-помощника ({@code ФормаКлиентскогоПриложения}, «Расширение
 * справочника», «Расширение отчета», формы сохранения / загрузки настроек
 * и т.п.).
 * <p>
 * Параметры формы не являются ни свойствами, ни методами: это ключи структуры,
 * передаваемой в {@code ОткрытьФорму(…, ПараметрыФормы)} /
 * {@code ПолучитьФорму(…)}, и читаемой в форме через свойство
 * {@code ЭтаФорма.Параметры}.
 *
 * @see ContextType#formParameters()
 */
public interface ContextFormParameter {

    /**
     * Имя параметра формы.
     */
    ContextName name();

    /**
     * Типы, которые может принимать параметр формы (блок «Тип:» в описании).
     */
    List<Context> types();

    /**
     * Описание параметра формы.
     */
    String description();

    /**
     * Признак ключевого параметра — на странице СП помечен чаптером
     * «Использование: Ключевой» (en: «Usage: Key Parameter»).
     * <p>
     * Ключевые параметры участвуют в вычислении ключа уникальности формы:
     * формы с разными значениями таких параметров открываются как разные окна
     * (например {@code Ключ} у формы объекта или
     * {@code КлючНазначенияИспользования} у формы клиентского приложения).
     */
    boolean isKey();

    /**
     * Версия платформы, начиная с которой доступен параметр (например {@code "8.2"}).
     * Пустая строка, если информация о версии отсутствует.
     */
    default String sinceVersion() {
        return "";
    }

    /**
     * Версия платформы, начиная с которой параметр помечен как не рекомендуемый
     * к использованию. Пустая строка, если параметр актуален.
     */
    default String deprecatedSinceVersion() {
        return "";
    }

    /**
     * Имена, рекомендованные в качестве замены устаревшего параметра.
     */
    default List<String> recommendedReplacements() {
        return List.of();
    }

    /**
     * Имена связанных контекстов и их членов — блок «См. также:»
     * (члены квалифицированы владельцем: {@code Владелец.Член}).
     */
    default List<String> seeAlso() {
        return List.of();
    }
}
