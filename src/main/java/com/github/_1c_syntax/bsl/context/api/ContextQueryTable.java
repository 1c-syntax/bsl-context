package com.github._1c_syntax.bsl.context.api;

import java.util.Collections;
import java.util.List;
import java.util.Optional;

/**
 * Таблица языка запросов — то, что можно поставить в секцию {@code ИЗ}
 * ({@code Справочник.<Имя справочника>}, {@code РегистрНакопления.<Имя
 * регистра накопления>.Остатки}).
 * <p>
 * Имя таблицы шаблонное: часть, которую задаёт платформа, записана
 * двуязычной парой, а имя конкретного объекта метаданных стоит
 * плейсхолдером. По этому плейсхолдеру потребитель и сопоставляет
 * таблицу с видом объекта.
 */
public interface ContextQueryTable extends Context {

    @Override
    default ContextKind kind() {
        return ContextKind.QUERY_TABLE;
    }

    /**
     * Поля таблицы.
     */
    default List<ContextQueryTableField> fields() {
        return Collections.emptyList();
    }

    /**
     * Поддержка корреспонденции у регистра бухгалтерии, которому принадлежит
     * таблица. Синтакс-помощник описывает таблицы регистра бухгалтерии дважды —
     * отдельно «с поддержкой корреспонденции» и «без», — и наборы полей у них
     * не совпадают: например, в основной таблице без корреспонденции есть
     * {@code Счет} и {@code ВидДвижения}, а с корреспонденцией вместо них —
     * {@code СчетДт} / {@code СчетКт} и измерения с ресурсами в вариантах
     * {@code Дт} / {@code Кт}. Имя таблицы при этом одно и то же, поэтому
     * выбрать нужную можно только по этому признаку.
     * <p>
     * Пусто у всех остальных таблиц: к ним корреспонденция неприменима.
     */
    default Optional<Boolean> correspondence() {
        return Optional.empty();
    }
}
