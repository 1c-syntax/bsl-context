package com.github._1c_syntax.bsl.context.api;

import java.util.List;
import java.util.Optional;

/**
 * Таблица языка запросов — источник данных в предложении {@code ИЗ}:
 * основная таблица прикладного объекта ({@code Справочник.<Имя справочника>},
 * {@code Документ.<Имя документа>}) или виртуальная таблица регистра
 * ({@code РегистрНакопления.<Имя регистра накопления>.Остатки},
 * {@code РегистрСведений.<Имя регистра сведений>.СрезПоследних}).
 * <p>
 * Источник — ветка {@code tables/} в {@code shcntx_*.hbk}; в дереве
 * синтакс-помощника это раздел «Работа с запросами» → «Таблицы запросов».
 * <p>
 * Намеренно <b>не</b> наследует {@link Context}: таблица существует только
 * внутри текста запроса и не является контекстом встроенного языка. Общего
 * у них лишь двуязычное имя и описание — у таблиц нет ни доступности по
 * клиентам, ни версии появления, ни «См. также» (в HBK этих блоков на
 * страницах {@code tables/} просто нет).
 *
 * @see QueryContextProvider#getTables()
 */
public interface ContextQueryTable {

    /**
     * Имя таблицы: {@code Справочник.<Имя справочника>},
     * {@code РегистрСведений.<Имя регистра сведений>.СрезПоследних}.
     */
    ContextName name();

    /**
     * Поля таблицы — то, что можно выбрать в списке выборки
     * ({@code Ссылка}, {@code Код}, {@code <Имя реквизита>} …).
     */
    List<ContextQueryTableField> fields();

    /**
     * Параметры виртуальной таблицы — то, что указывается в скобках после
     * её имени ({@code РегистрСведений.Цены.СрезПоследних(&Дата, Товар = &Товар)}).
     * У основных таблиц параметров нет — пустой список.
     */
    default List<ContextQueryTableParameter> parameters() {
        return List.of();
    }

    /**
     * Поддержка корреспонденции у регистра бухгалтерии, которому принадлежит
     * таблица.
     * <p>
     * Синтакс-помощник описывает таблицы регистра бухгалтерии дважды —
     * отдельно «с поддержкой корреспонденции» и «без», — и наборы полей у них
     * не совпадают: в основной таблице без корреспонденции есть {@code Счет}
     * и {@code ВидДвижения}, а с корреспонденцией вместо них — {@code СчетДт}
     * / {@code СчетКт} и измерения с ресурсами в вариантах {@code Дт} /
     * {@code Кт}. Имя таблицы при этом одно и то же, поэтому выбрать нужную
     * можно только по этому признаку.
     * <p>
     * Пусто у всех остальных таблиц: к ним корреспонденция неприменима.
     */
    default Optional<Boolean> correspondence() {
        return Optional.empty();
    }

    /**
     * Сырая строка чаптера «Синтаксис» со страницы таблицы, например
     * {@code РегистрСведений.<Имя регистра сведений>.СрезПоследних}.
     */
    default String syntaxText() {
        return "";
    }

    /**
     * Описание таблицы из синтакс-помощника.
     */
    String description();

    /**
     * Английское описание таблицы — со страницы того же пути в en-HBK.
     * Пусто, если en-HBK не подгружен или парной страницы нет.
     */
    default String descriptionEn() {
        return "";
    }

    /**
     * Примеры запросов со страницы таблицы (блоки «Пример:»).
     */
    default List<String> examples() {
        return List.of();
    }

    /**
     * Те же примеры с парной en-страницы — запрос в них записан
     * английскими ключевыми словами.
     */
    default List<String> examplesEn() {
        return List.of();
    }

    /**
     * Признак generic-имени: конкретизация ({@code Справочник.Контрагенты})
     * приходит из конфигурации. Таких таблиц почти все — 58 из 59 в 8.3.27.
     */
    default boolean isGeneric() {
        return ContextNames.isGeneric(name());
    }

    /**
     * Имена placeholder'ов в имени таблицы (без угловых скобок): для
     * {@code РегистрСведений.<Имя регистра сведений>.СрезПоследних} —
     * {@code ["Имя регистра сведений"]}.
     */
    default List<String> typeParameters() {
        return ContextNames.typeParameters(name());
    }
}
