package com.github._1c_syntax.bsl.context.api;

import java.util.List;

/**
 * Параметр виртуальной таблицы языка запросов — то, что указывается в
 * скобках после её имени: {@code Период}, {@code Условие},
 * {@code Периодичность}, {@code МетодДополненияПериодов}.
 * <p>
 * На странице параметра обязательность записана в самом заголовке
 * («Период (необязательный)»), а типы — в блоке «Тип параметра:»; у
 * параметров-выражений языка запросов ({@code Условие}) типов нет.
 *
 * @see ContextQueryTable#parameters()
 */
public interface ContextQueryTableParameter {

    /**
     * Имя параметра.
     */
    ContextName name();

    /**
     * Типы значения параметра (блок «Тип параметра:»). Пустой список, если
     * параметр принимает выражение языка запросов, а не значение.
     */
    List<Context> types();

    /**
     * Признак обязательного параметра. В HBK обязательность помечена
     * суффиксом «(необязательный)» в заголовке; без суффикса параметр
     * считается обязательным.
     */
    boolean isRequired();

    /**
     * Описание параметра.
     */
    String description();

    /**
     * Английское описание параметра — со страницы того же пути в en-HBK.
     * Пусто, если en-HBK не подгружен или парной страницы нет.
     */
    default String descriptionEn() {
        return "";
    }
}
